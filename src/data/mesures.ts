const SENS_LABEL: Record<Sens, string> = { L: 'Longueur', H: 'Hauteur', E: 'Envergure' };

/** « 1,5 » plutôt que « 1.5 », sans décimale inutile */
const fr = (n: number, digits = 1) => n.toLocaleString('fr-FR', { maximumFractionDigits: digits });

export function formatPoids(kg: number): string {
  if (kg >= 1000) return `${fr(kg / 1000, kg < 10000 ? 1 : 0)} t`;
  if (kg >= 1) return `${fr(kg, kg < 10 ? 1 : 0)} kg`;
  if (kg >= 0.001) return `${fr(kg * 1000, kg < 0.01 ? 1 : 0)} g`;
  if (kg >= 0.000001) return `${fr(kg * 1e6, kg < 0.00001 ? 1 : 0)} mg`;
  return `${fr(kg * 1e9, 0)} µg`;
}

export function formatTaille(m: number): string {
  if (m >= 1) return `${fr(m, 1)} m`;
  if (m >= 0.01) return `${fr(m * 100, m < 0.1 ? 1 : 0)} cm`;
  return `${fr(m * 1000, 1)} mm`;
}

export function formatLongevite(ans: number): string {
  if (ans >= 2) return `${fr(ans, 0)} ans`;
  if (ans >= 1) return `${fr(ans, 1)} an${ans >= 1.5 ? 's' : ''}`;
  const mois = Math.round(ans * 12);
  if (mois >= 1) return `${mois} mois`;
  const jours = Math.round(ans * 365);
  return `${jours} jour${jours > 1 ? 's' : ''}`;
}

export interface MesuresAffichees {
  poids?: string;
  taille?: string;
  tailleLabel: string;
  longevite?: string;
}

/** Mesures lisibles d'une espèce, ou null (cartes Mythe, espèce sans données). */
export function mesuresOf(id: string): MesuresAffichees | null {
  const m = MESURES[id];
  if (!m) return null;
  const [poids, taille, sens, longevite] = m;
  return {
    poids: poids != null ? formatPoids(poids) : undefined,
    taille: taille != null ? formatTaille(taille) : undefined,
    tailleLabel: SENS_LABEL[sens],
    longevite: longevite != null ? formatLongevite(longevite) : undefined,
  };
}
