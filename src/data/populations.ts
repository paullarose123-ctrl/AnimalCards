/** Chiens dans le monde, toutes races confondues : sert à la rareté des races, qui n'ont pas de recensement propre. */
export const CHIENS_DANS_LE_MONDE = 900_000_000;

const DOMESTIQUES = new Set(['dromadaire', 'lama', 'yak', 'alpaga']);

// espace insécable ordinaire : l'espace fine de toLocaleString n'existe pas dans toutes les polices
const fr = (n: number, digits = 0) => n.toLocaleString('fr-FR', { maximumFractionDigits: digits }).replace(/ /g, ' ');
const SUPERSCRIPT = '⁰¹²³⁴⁵⁶⁷⁸⁹';

/** « 23 000 », « 1,5 M », « 26 Md », « 2·10¹⁶ » (au-delà de mille milliards). */
export function formatPopulation(n: number): string {
  if (n < 10_000) return fr(Math.round(n / 10) * 10 || n);
  if (n < 1_000_000) return fr(Math.round(n / 1000) * 1000);
  if (n < 1e9) return `${fr(n / 1e6, n < 1e7 ? 1 : 0)} M`;
  if (n < 1e12) return `${fr(n / 1e9, n < 1e10 ? 1 : 0)} Md`;
  const exp = Math.floor(Math.log10(n));
  const mantissa = Math.round(n / 10 ** exp);
  const sup = String(exp)
    .split('')
    .map((d) => SUPERSCRIPT[Number(d)])
    .join('');
  return mantissa === 1 ? `10${sup}` : `${mantissa}·10${sup}`;
}

export interface PopulationAffichee {
  /** valeur courte pour la carte : « 23 000 », « Éteint » */
  value: string;
  /** libellé de la fiche */
  label: string;
  extinct: boolean;
}

/** Population restante d'une espèce, ou null (carte Mythe, espèce sans estimation). */
export function populationOf(athlete: Athlete): PopulationAffichee | null {
  if (athlete.mythe || athlete.race) return null;
  if (athlete.retired || athlete.sport === 'prehistoire') return { value: 'Éteint', label: 'Population', extinct: true };
  const n = POPULATIONS[athlete.id];
  if (n == null) return null;
  const domestic = athlete.sport === 'ferme' || DOMESTIQUES.has(athlete.id);
  return { value: formatPopulation(n), label: domestic ? 'Population mondiale' : 'Population sauvage', extinct: false };
}
